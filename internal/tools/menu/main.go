// Command menu writes cmd/demo/menu_gen.go: the Tabler preview's menu (shared/data/menu.json) for the demo's
// navigation. Run it from the module root with the path of a Tabler checkout:
//
//	go run ./internal/tools/menu ~/work/tabler
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
)

type node struct {
	Title, URL, Icon, Badge, Section, Color string
	Columns                                 int
	Children                                []node
}

// entries decodes a JSON object of entries in its order (a Go map would lose it).
func entries(d *json.Decoder) []node {
	expect(d, json.Delim('{'))
	var ns []node
	for d.More() {
		d.Token() // the entry's key
		ns = append(ns, entry(d))
	}
	expect(d, json.Delim('}'))
	return ns
}

func entry(d *json.Decoder) node {
	expect(d, json.Delim('{'))
	var n node
	for d.More() {
		t, _ := d.Token()
		switch t {
		case "children":
			n.Children = entries(d)
		case "columns":
			d.Decode(&n.Columns)
		default:
			var s string
			if err := d.Decode(&s); err != nil {
				log.Fatalf("%v: %v", t, err)
			}
			switch t {
			case "title":
				n.Title = s
			case "url":
				n.URL = strings.TrimSuffix(s, ".html")
			case "icon":
				n.Icon = "ti-" + s
			case "badge":
				n.Badge = s
			case "section":
				n.Section = s
			case "color":
				n.Color = s
			}
		}
	}
	expect(d, json.Delim('}'))
	return n
}

func expect(d *json.Decoder, want json.Token) {
	if t, err := d.Token(); err != nil || t != want {
		log.Fatalf("menu.json: want %v, got %v (%v)", want, t, err)
	}
}

func write(b *bytes.Buffer, ns []node) {
	for _, n := range ns {
		b.WriteString("{")
		for _, f := range [][2]string{{"Title", n.Title}, {"URL", n.URL}, {"Icon", n.Icon}, {"Badge", n.Badge}, {"Section", n.Section}, {"Color", n.Color}} {
			if f[1] != "" {
				fmt.Fprintf(b, "%s: %q, ", f[0], f[1])
			}
		}
		if n.Columns > 0 {
			fmt.Fprintf(b, "Columns: %d, ", n.Columns)
		}
		if len(n.Children) > 0 {
			b.WriteString("Children: []menuNode{\n")
			write(b, n.Children)
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: menu <tabler checkout>")
	}
	f, err := os.Open(filepath.Join(os.Args[1], "shared/data/menu.json"))
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	menu := entries(json.NewDecoder(f))

	var b bytes.Buffer
	b.WriteString(`// Code generated by go run ./internal/tools/menu from Tabler's shared/data/menu.json (the preview's menu); DO NOT EDIT.

package main

// menuNode is an entry of the preview's menu; URL is a page name (or an external URL).
type menuNode struct {
	Title, URL, Icon, Badge, Section, Color string
	Columns                                 int
	Children                                []menuNode
}

var previewMenu = []menuNode{
`)
	write(&b, menu)
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("cmd/demo/menu_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
