// Command charts writes cmd/demo/charts_gen.go: the charts of the Tabler preview (shared/data/charts.json)
// as chart.Props. Run it from the module root with the path of a Tabler checkout:
//
//	go run ./internal/tools/charts ~/work/tabler
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type serie struct {
	Name         string          `json:"name"`
	Type         string          `json:"type"`
	Data         json.RawMessage `json:"data"`
	Color        string          `json:"color"`
	ColorOpacity string          `json:"color-opacity"`
	Candlestick  json.RawMessage `json:"candlestick-data"`
	Heatmap      json.RawMessage `json:"heatmap-data"`
	Treemap      json.RawMessage `json:"treemap-data"`
	Range        json.RawMessage `json:"range-data"`
	Box          json.RawMessage `json:"box-data"`
	Bubble       json.RawMessage `json:"bubble-data"`
}

type annotation struct {
	Value any    `json:"value"`
	Label string `json:"label"`
	Color string `json:"color"`
	Dash  *int   `json:"dash"`
}

type yaxis struct {
	SeriesName string   `json:"series-name"`
	Title      string   `json:"title"`
	Opposite   bool     `json:"opposite"`
	Min        *float64 `json:"min"`
	Max        *float64 `json:"max"`
}

type data struct {
	Type           string       `json:"type"`
	Height         float64      `json:"height"`
	Series         []serie      `json:"series"`
	Categories     []any        `json:"categories"`
	Datetime       bool         `json:"datetime"`
	StartDate      string       `json:"start-date"`
	Sparkline      bool         `json:"sparkline"`
	Stacked        bool         `json:"stacked"`
	Toolbar        bool         `json:"toolbar"`
	Horizontal     bool         `json:"horizontal"`
	Funnel         bool         `json:"funnel"`
	Legend         bool         `json:"legend"`
	Datalabels     bool         `json:"datalabels"`
	ShowDataLabels bool         `json:"show-data-labels"`
	Color          string       `json:"color"`
	Colors         []string     `json:"colors"`
	RadarSize      float64      `json:"radar-size"`
	StrokeWidth    any          `json:"stroke-width"`
	StrokeDash     any          `json:"stroke-dash"`
	StrokeCurve    string       `json:"stroke-curve"`
	ShowX          bool         `json:"show-x"`
	XFormatter     string       `json:"x-formatter"`
	YFormatter     string       `json:"y-formatter"`
	YMax           *float64     `json:"y-max"`
	YTooltip       bool         `json:"y-tooltip"`
	YAxes          []yaxis      `json:"y-axes"`
	HideTooltip    bool         `json:"hide-tooltip"`
	HidePoints     bool         `json:"hide-points"`
	ShowMarkers    bool         `json:"show-markers"`
	AnnotationsX   []annotation `json:"annotations-x"`
	AnnotationsY   []annotation `json:"annotations-y"`
	Group          string       `json:"group"`
	BrushTarget    string       `json:"brush-target"`
	SelectionFrom  float64      `json:"selection-from"`
	SelectionTo    float64      `json:"selection-to"`
}

var formatters = map[string]string{"thousands": "chart.Thousands", "suffix-k": "chart.SuffixK"}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: charts <tabler checkout>")
	}
	raw, err := os.ReadFile(filepath.Join(os.Args[1], "shared/data/charts.json"))
	if err != nil {
		log.Fatal(err)
	}
	var all map[string]map[string]json.RawMessage
	if err := json.Unmarshal(raw, &all); err != nil {
		log.Fatal(err)
	}
	ids := make([]string, 0, len(all))
	for id := range all {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./internal/tools/charts from Tabler's shared/data/charts.json; DO NOT EDIT.\n\n")
	b.WriteString("package main\n\nimport \"github.com/mind-vm/tabler-templ/chart\"\n\n")
	b.WriteString("// tablerCharts are the charts of the Tabler preview by their id in charts.json.\n")
	b.WriteString("var tablerCharts = map[string]chart.Props{\n")
	for _, id := range ids {
		m := all[id]
		// extend: the base chart's fields, overridden by this one's.
		if ext, ok := m["extend"]; ok {
			var base string
			json.Unmarshal(ext, &base)
			merged := map[string]json.RawMessage{}
			for k, v := range all[base] {
				merged[k] = v
			}
			for k, v := range m {
				merged[k] = v
			}
			m = merged
		}
		j, _ := json.Marshal(m)
		var d data
		if err := json.Unmarshal(j, &d); err != nil {
			log.Fatalf("%s: %v", id, err)
		}
		fmt.Fprintf(&b, "%q: {\n", id)
		props(&b, d)
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n// tablerChartNames are the names of the charts that have one.\nvar tablerChartNames = map[string]string{\n")
	for _, id := range ids {
		var name string
		json.Unmarshal(all[id]["name"], &name)
		if name != "" {
			fmt.Fprintf(&b, "%q: %q,\n", id, name)
		}
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		os.WriteFile("cmd/demo/charts_gen.go", b.Bytes(), 0o644)
		log.Fatal(err)
	}
	if err := os.WriteFile("cmd/demo/charts_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func props(b *bytes.Buffer, d data) {
	str := func(field, v string) {
		if v != "" {
			fmt.Fprintf(b, "%s: %q,\n", field, v)
		}
	}
	flag := func(field string, v bool) {
		if v {
			fmt.Fprintf(b, "%s: true,\n", field)
		}
	}
	if d.Type != "" {
		fmt.Fprintf(b, "Type: chart.%s,\n", strings.ToUpper(d.Type[:1])+d.Type[1:])
	}
	if d.Height != 0 {
		fmt.Fprintf(b, "Height: %v,\n", d.Height)
	}
	if len(d.Series) > 0 {
		b.WriteString("Series: []chart.Serie{\n")
		for _, s := range d.Series {
			b.WriteString("{")
			str("Name", s.Name)
			str("Type", s.Type)
			str("Color", s.Color)
			str("ColorOpacity", s.ColorOpacity)
			if len(s.Data) > 0 {
				var one float64
				if json.Unmarshal(s.Data, &one) == nil {
					fmt.Fprintf(b, "Data: []float64{%v},\n", one)
				} else {
					fmt.Fprintf(b, "Data: []float64{%s},\n", strings.Trim(string(s.Data), "[]"))
				}
			}
			for _, pts := range []json.RawMessage{s.Candlestick, s.Heatmap, s.Treemap, s.Range, s.Box, s.Bubble} {
				if len(pts) == 0 {
					continue
				}
				var ps []map[string]any
				json.Unmarshal(pts, &ps)
				b.WriteString("Points: []chart.Point{")
				for _, p := range ps {
					fmt.Fprintf(b, "{X: %s, Y: %s", lit(p["x"]), lit(p["y"]))
					if z, ok := p["z"]; ok {
						fmt.Fprintf(b, ", Z: %s", lit(z))
					}
					b.WriteString("},")
				}
				b.WriteString("},\n")
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	if d.Categories != nil {
		b.WriteString("Categories: []string{")
		for _, c := range d.Categories {
			fmt.Fprintf(b, "%q,", fmt.Sprint(c))
		}
		b.WriteString("},\n")
	}
	flag("Datetime", d.Datetime)
	str("StartDate", d.StartDate)
	flag("Sparkline", d.Sparkline)
	flag("Stacked", d.Stacked)
	flag("Toolbar", d.Toolbar)
	flag("Horizontal", d.Horizontal)
	flag("Funnel", d.Funnel)
	flag("Legend", d.Legend)
	// datalabels only reaches bar and area charts in Tabler's chart-script; show-data-labels all of them.
	flag("DataLabels", d.Datalabels && (d.Type == "" || d.Type == "bar" || d.Type == "area") || d.ShowDataLabels)
	str("Color", d.Color)
	if d.Colors != nil {
		fmt.Fprintf(b, "Colors: %#v,\n", d.Colors)
	}
	if d.RadarSize != 0 {
		fmt.Fprintf(b, "RadarSize: %v,\n", d.RadarSize)
	}
	floats := func(field string, v any) {
		switch v := v.(type) {
		case float64:
			fmt.Fprintf(b, "%s: []float64{%v},\n", field, v)
		case []any:
			fmt.Fprintf(b, "%s: []float64{", field)
			for _, x := range v {
				fmt.Fprintf(b, "%v,", x)
			}
			b.WriteString("},\n")
		}
	}
	floats("StrokeWidth", d.StrokeWidth)
	floats("StrokeDash", d.StrokeDash)
	str("StrokeCurve", d.StrokeCurve)
	flag("ShowX", d.ShowX)
	if f := formatters[d.XFormatter]; f != "" {
		fmt.Fprintf(b, "XFormatter: %s,\n", f)
	}
	if f := formatters[d.YFormatter]; f != "" {
		fmt.Fprintf(b, "YFormatter: %s,\n", f)
	}
	if d.YMax != nil {
		fmt.Fprintf(b, "YMax: ptr(float64(%v)),\n", *d.YMax)
	}
	flag("YTooltip", d.YTooltip)
	if d.YAxes != nil {
		b.WriteString("YAxes: []chart.YAxis{")
		for _, a := range d.YAxes {
			b.WriteString("{")
			str("SeriesName", a.SeriesName)
			str("Title", a.Title)
			flag("Opposite", a.Opposite)
			if a.Min != nil {
				fmt.Fprintf(b, "Min: ptr(float64(%v)),\n", *a.Min)
			}
			if a.Max != nil {
				fmt.Fprintf(b, "Max: ptr(float64(%v)),\n", *a.Max)
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	flag("HideTooltip", d.HideTooltip)
	flag("HidePoints", d.HidePoints)
	flag("ShowMarkers", d.ShowMarkers)
	annotations := func(field string, as []annotation) {
		if as == nil {
			return
		}
		fmt.Fprintf(b, "%s: []chart.Annotation{", field)
		for _, a := range as {
			fmt.Fprintf(b, "{Value: %s,", lit(a.Value))
			str("Label", a.Label)
			str("Color", a.Color)
			if a.Dash != nil {
				fmt.Fprintf(b, "Dash: ptr(%d),\n", *a.Dash)
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	annotations("AnnotationsX", d.AnnotationsX)
	annotations("AnnotationsY", d.AnnotationsY)
	str("Group", d.Group)
	str("BrushTarget", d.BrushTarget)
	if d.SelectionFrom != 0 {
		fmt.Fprintf(b, "SelectionFrom: %v, SelectionTo: %v,\n", int64(d.SelectionFrom), int64(d.SelectionTo))
	}
}

// lit is a JSON value as a Go literal for an any field.
func lit(v any) string {
	switch v := v.(type) {
	case string:
		return fmt.Sprintf("%q", v)
	case float64:
		return fmt.Sprintf("%v", v)
	case []any:
		var s []string
		for _, x := range v {
			s = append(s, fmt.Sprint(x))
		}
		return "[]float64{" + strings.Join(s, ", ") + "}"
	}
	return "nil"
}
