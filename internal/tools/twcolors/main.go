// Command twcolors writes themes/colors_gen.go: the color palettes of Tailwind CSS (MIT), which shadcn's
// themes are built from, read from its theme.css on jsDelivr. Run it from the module root:
//
//	go run ./internal/tools/twcolors 4.3.3
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strconv"
)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: twcolors <tailwindcss version>")
	}
	version := os.Args[1]
	resp, err := http.Get("https://cdn.jsdelivr.net/npm/tailwindcss@" + version + "/theme.css")
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatal(resp.Status)
	}
	css, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	re := regexp.MustCompile(`--color-([a-z]+)-(\d+):\s*(oklch\([^)]*\))`)
	palettes := map[string]map[int]string{}
	for _, m := range re.FindAllSubmatch(css, -1) {
		name, value := string(m[1]), string(m[3])
		shade, _ := strconv.Atoi(string(m[2]))
		if palettes[name] == nil {
			palettes[name] = map[int]string{}
		}
		palettes[name][shade] = value
	}
	names := make([]string, 0, len(palettes))
	for n := range palettes {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./internal/tools/twcolors %s; DO NOT EDIT.\n\npackage themes\n\n", version)
	fmt.Fprintf(&b, "// TailwindVersion is the Tailwind CSS release the palettes come from.\nconst TailwindVersion = %q\n\n", version)
	b.WriteString("// palettes are Tailwind CSS's colors (MIT License) by name and shade, 50 to 950.\nvar palettes = map[string]map[int]string{\n")
	for _, n := range names {
		shades := make([]int, 0, len(palettes[n]))
		for s := range palettes[n] {
			shades = append(shades, s)
		}
		sort.Ints(shades)
		fmt.Fprintf(&b, "%q: {", n)
		for _, s := range shades {
			fmt.Fprintf(&b, "%d: %q, ", s, palettes[n][s])
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("themes/colors_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d palettes", len(names))
}
