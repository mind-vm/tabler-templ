// Command filledicons writes icon/filled_gen.go: the code points of the filled Tabler icons, read from
// the webfont's tabler-icons-filled.css. Run it from the module root:
//
//	go run ./internal/tools/filledicons 3.49.0
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strconv"
)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: filledicons <tabler-icons-webfont version>")
	}
	version := os.Args[1]
	resp, err := http.Get("https://cdn.jsdelivr.net/npm/@tabler/icons-webfont@" + version + "/dist/tabler-icons-filled.min.css")
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	css, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	re := regexp.MustCompile(`\.(ti-[a-z0-9-]+):before\{content:"\\([0-9a-f]+)"`)
	glyphs := map[string]int64{}
	for _, m := range re.FindAllSubmatch(css, -1) {
		cp, err := strconv.ParseInt(string(m[2]), 16, 32)
		if err != nil {
			log.Fatal(err)
		}
		glyphs[string(m[1])] = cp
	}
	names := make([]string, 0, len(glyphs))
	for n := range glyphs {
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./internal/tools/filledicons %s; DO NOT EDIT.\n\npackage icon\n\n", version)
	fmt.Fprintf(&b, "// FilledVersion is the tabler-icons-webfont version the filled glyphs come from.\nconst FilledVersion = %q\n\n", version)
	b.WriteString("// filled maps an icon name to its glyph in the filled webfont (tabler-icons-filled).\nvar filled = map[string]rune{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: 0x%x,\n", n, glyphs[n])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("icon/filled_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d filled icons", len(names))
}
