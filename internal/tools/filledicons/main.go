// Command filledicons writes icon/filled_gen.go, the code points of the filled Tabler icons read from the
// webfont's tabler-icons-filled.css, and cmd/static/names_gen.go, the names of all outline icons read from
// tabler-icons.css (cmd/static -check tells icons from words with it, without the network). Run it from the
// module root:
//
//	go run ./internal/tools/filledicons 3.49.0
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strconv"
)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: filledicons <tabler-icons-webfont version>")
	}
	version := os.Args[1]
	glyphs := read(version, "tabler-icons-filled.min.css")
	names := sorted(glyphs)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./internal/tools/filledicons %s; DO NOT EDIT.\n\npackage icon\n\n", version)
	fmt.Fprintf(&b, "// FilledVersion is the tabler-icons-webfont version the filled glyphs come from.\nconst FilledVersion = %q\n\n", version)
	b.WriteString("// filled maps an icon name to its glyph in the filled webfont (tabler-icons-filled).\nvar filled = map[string]rune{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: 0x%x,\n", n, glyphs[n])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("icon/filled_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d filled icons", len(names))

	outline := sorted(read(version, "tabler-icons.min.css"))
	b.Reset()
	fmt.Fprintf(&b, "// Code generated by go run ./internal/tools/filledicons %s; DO NOT EDIT.\n\npackage main\n\n", version)
	fmt.Fprintf(&b, "// iconsVersion is the tabler-icons-webfont version of iconNames.\nconst iconsVersion = %q\n\n", version)
	b.WriteString("// iconNames are the classes of all outline icons; -check tells icons from words like \"ti-…\" with them.\nvar iconNames = []string{\n")
	for _, n := range outline {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n")
	if src, err = format.Source(b.Bytes()); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("cmd/static/names_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d outline icons", len(outline))
}

var rule = regexp.MustCompile(`\.(ti-[a-z0-9-]+):before\{content:"\\([0-9a-f]+)"`)

// read fetches a stylesheet of the webfont and maps its icon classes to their code points.
func read(version, name string) map[string]int64 {
	resp, err := http.Get("https://cdn.jsdelivr.net/npm/@tabler/icons-webfont@" + version + "/dist/" + name)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", name, resp.Status)
	}
	css, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	glyphs := map[string]int64{}
	for _, m := range rule.FindAllSubmatch(css, -1) {
		cp, err := strconv.ParseInt(string(m[2]), 16, 32)
		if err != nil {
			log.Fatal(err)
		}
		glyphs[string(m[1])] = cp
	}
	if len(glyphs) == 0 {
		log.Fatalf("%s: no icons", name)
	}
	return glyphs
}

func sorted(m map[string]int64) []string {
	names := make([]string, 0, len(m))
	for n := range m {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}
