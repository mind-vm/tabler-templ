// Package catalog is the checklist of the port: every Tabler component, every composed part of the
// Tabler preview and every preview page, each with its status in this module. ROADMAP.md and the index
// of cmd/demo are generated from it (go run ./internal/catalog/roadmap).
//
// The lists were seeded from the Tabler sources (docs/content/ui, shared/components, preview); the
// status of an entry is maintained by hand whenever a package or demo page changes.
package catalog

import (
	"fmt"
	"io"
	"strings"
)

// Status of an entry. The zero value is Open.
type Status int

const (
	Open    Status = iota
	Partial        // usable, but variants or parts of the Tabler original are missing (see Note)
	Done           // matches the Tabler original
)

func (s Status) String() string {
	return [...]string{"open", "partial", "done"}[s]
}

// Component is a page of the Tabler docs under ui/components or ui/forms.
type Component struct {
	Name    string
	Doc     string   // path below https://docs.tabler.io/; empty for parts without a docs page
	Astro   []string // Tabler's Astro components in shared/ui/ that the package mirrors
	Status  Status
	Package string // import path below the module, e.g. "button"
	Note    string
}

// Block is a composed part of the preview in Tabler's shared/components/.
type Block struct {
	Source  string // path below shared/components/, without .astro
	Status  Status
	Package string
	Note    string
}

// Page is a page of the Tabler preview (preview.tabler.io/<Name>.html).
type Page struct {
	Name        string
	Title       string
	Group       string
	Description string
	Status      Status // Done or Partial when cmd/demo rebuilds it
	Note        string
}

// Own lists blocks of this module that have no counterpart in the Tabler preview.
var Own = []struct{ Package, Text string }{
	{"blocks/shell", "page frame with sidebar, sticky header, breadcrumbs, page header and flash message"},
	{"blocks/listpage", "list page: search, filters and pagination read from the URL"},
	{"blocks/create", "create page: post form with footer"},
	{"blocks/detail", "detail page: sections with edit dialogs that reopen after a failed save"},
	{"blocks/history", "change history as a timeline"},
	{"blocks/signin", "sign-in page with its own look and an account picker (Tabler's own look: blocks/auth)"},
}

// Groups returns the page groups in catalog order.
func Groups() []string {
	var gs []string
	for _, p := range Pages {
		if len(gs) == 0 || gs[len(gs)-1] != p.Group {
			gs = append(gs, p.Group)
		}
	}
	return gs
}

// Find returns the page with the given name.
func Find(name string) (Page, bool) {
	for _, p := range Pages {
		if p.Name == name {
			return p, true
		}
	}
	return Page{}, false
}

const (
	docsURL    = "https://docs.tabler.io/"
	sourceURL  = "https://github.com/tabler/tabler/blob/dev/shared/"
	previewURL = "https://preview.tabler.io/"
)

func count[T any](items []T, status func(T) Status) string {
	var n [3]int
	for _, it := range items {
		n[status(it)]++
	}
	return fmt.Sprintf("%d done, %d partial, %d open (of %d)", n[Done], n[Partial], n[Open], len(items))
}

func check(s Status) string {
	if s == Done {
		return "- [x] "
	}
	return "- [ ] "
}

func detail(s Status, pkg, note string) string {
	var parts []string
	if pkg != "" {
		parts = append(parts, "`"+pkg+"`")
	}
	if s == Partial {
		parts = append(parts, "partial")
	}
	if note != "" {
		parts = append(parts, note)
	}
	if len(parts) == 0 {
		return ""
	}
	return " — " + strings.Join(parts, ", ")
}

// Roadmap writes ROADMAP.md.
func Roadmap(w io.Writer) {
	p := func(format string, a ...any) { fmt.Fprintf(w, format+"\n", a...) }
	p("# Roadmap")
	p("")
	p("<!-- Generated by `go run ./internal/catalog/roadmap` from internal/catalog. Edit the catalog, not this file. -->")
	p("")
	p("The goal is all of [Tabler](https://tabler.io) in Go and templ: every component of the Tabler docs as a")
	p("package, every composed part of the Tabler preview as a block, and every preview page rebuilt in `cmd/demo`.")
	p("A ticked box matches the Tabler original; *partial* means usable, with the missing variants named.")
	p("")
	p("| | Status |")
	p("|---|---|")
	p("| Components | %s |", count(Components, func(c Component) Status { return c.Status }))
	p("| Blocks | %s |", count(Blocks, func(b Block) Status { return b.Status }))
	p("| Preview pages | %s |", count(Pages, func(pg Page) Status { return pg.Status }))
	p("")
	p("## Plan")
	p("")
	p("One pull request per step:")
	p("")
	p("1. Navigation and overlays: dropdown, tabs, nav, breadcrumb, offcanvas, toast, tooltip, popover")
	p("2. Showing data: avatar, list group, timeline, datagrid, progress, steps, status, ribbon, empty, tracking")
	p("3. Forms: input group, select group, image check, color check, OTP, password strength, validation, floating labels")
	p("4. Sign-in and account blocks: sign-in (4 variants), sign-up, forgot password, 2FA, auth lock, onboarding")
	p("5. Blocks from `shared/components` (cards, modals, navbar) and the app pages: settings, profile, pricing, invoice, error pages, wizard; the layouts")
	p("6. The remaining preview pages in `cmd/demo`, screenshots in the README")
	p("7. Starter kit `cmd/new`")
	p("")
	p("Plugins (date picker, dropzone, charts …) only where they cost little or an app needs them.")
	p("")
	p("## Components")
	p("")
	p("From the Tabler docs ([components](%sui/components), [forms](%sui/forms)); the Astro sources in", docsURL, docsURL)
	p("[`shared/ui`](%sui) show the props and variants the packages mirror.", sourceURL)
	p("")
	for _, c := range Components {
		src := ""
		if len(c.Astro) > 0 {
			src = " (" + strings.Join(c.Astro, ", ") + ")"
		}
		link := docsURL + c.Doc
		if c.Doc == "" {
			link = sourceURL + "ui/" + c.Astro[0] + ".astro"
		}
		p("%s[%s](%s)%s%s", check(c.Status), c.Name, link, src, detail(c.Status, c.Package, c.Note))
	}
	p("")
	p("## Blocks")
	p("")
	p("Composed parts of the preview, from [`shared/components`](%scomponents).", sourceURL)
	dir := ""
	for _, b := range Blocks {
		if d, _, _ := strings.Cut(b.Source, "/"); d != dir {
			dir = d
			p("")
			p("### %s", d)
			p("")
		}
		p("%s[%s](%scomponents/%s.astro)%s", check(b.Status), b.Source, sourceURL, b.Source, detail(b.Status, b.Package, b.Note))
	}
	p("")
	p("### Own blocks")
	p("")
	p("Blocks of this module without a counterpart in the preview, grown from the apps that use it:")
	p("")
	for _, o := range Own {
		p("- `%s`: %s", o.Package, o.Text)
	}
	p("")
	p("## Preview pages")
	p("")
	p("Every page of the [Tabler preview](%s), rebuilt in `cmd/demo` at `/<name>`.", previewURL)
	for _, g := range Groups() {
		p("")
		p("### %s", g)
		p("")
		for _, pg := range Pages {
			if pg.Group == g {
				p("%s[%s](%s%s.html) %s%s", check(pg.Status), pg.Name, previewURL, pg.Name, pg.Title, detail(pg.Status, "", pg.Note))
			}
		}
	}
}
