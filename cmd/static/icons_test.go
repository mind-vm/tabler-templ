// testdata holds a part of @tabler/icons-webfont 3.49.0 (MIT, testdata/LICENSE) with six icons, in the
// shape of the real stylesheet and font.
func fixture(t *testing.T) (string, []byte) {
	t.Helper()
	css, err := os.ReadFile("testdata/tabler-icons.min.css")
	if err != nil {
		t.Fatal(err)
	}
	woff2, err := os.ReadFile("testdata/tabler-icons.woff2")
	if err != nil {
		t.Fatal(err)
	}
	return string(css), woff2
}

func parse(t *testing.T, woff2 []byte) *font.SFNT {
	t.Helper()
	b, err := font.ToSFNT(woff2)
	if err != nil {
		t.Fatal(err)
	}
	f, err := font.ParseSFNT(b, 0)
	if err != nil {
		t.Fatal(err)
	}
	return f
}

// The subset has every used icon with the glyph of the original, and no other icon; words that are no
// icon are left out.
func TestSubset(t *testing.T) {
	css, woff2 := fixture(t)
	all := glyphs(css)
	if len(all) != 6 || all["ti-home"] != 0xeac1 {
		t.Fatalf("glyphs: %v", all)
	}
	used := map[string]bool{"ti-home": true, "ti-star": true, "ti-pencil": true, "ti-not-an-icon": true}
	sub, f, n, err := subset(css, woff2, used)
	if err != nil {
		t.Fatal(err)
	}
	if n != 3 || !strings.HasPrefix(sub, subsetMarker) || allIcons(sub) || !allIcons(css) {
		t.Errorf("%d icons:\n%s", n, sub)
	}
	if got := glyphs(sub); !reflect.DeepEqual(got, map[string]rune{"ti-home": 0xeac1, "ti-star": 0xeb2e, "ti-pencil": 0xeb04}) {
		t.Errorf("rules: %v", got)
	}
	if !strings.Contains(sub, `src:url("./fonts/tabler-icons.woff2") format("woff2")}`) || strings.Contains(sub, "?v") ||
		!strings.Contains(sub, ".ti{font-family:") || !strings.Contains(sub, "License") {
		t.Errorf("head of the stylesheet:\n%s", sub)
	}
	if len(f) >= len(woff2) {
		t.Errorf("font %d bytes, not smaller than %d", len(f), len(woff2))
	}
	orig, cut := parse(t, woff2), parse(t, f)
	for name := range used {
		cp, ok := all[name]
		if !ok {
			continue
		}
		a, b := orig.GlyphIndex(cp), cut.GlyphIndex(cp)
		if b == 0 {
			t.Errorf("%s (U+%X) not in the font", name, cp)
			continue
		}
		x0, y0, x1, y1 := orig.GlyphBounds(a)
		u0, v0, u1, v1 := cut.GlyphBounds(b)
		if [4]int16{x0, y0, x1, y1} != [4]int16{u0, v0, u1, v1} || orig.GlyphAdvance(a) != cut.GlyphAdvance(b) {
			t.Errorf("%s: other glyph", name)
		}
	}
	for _, name := range []string{"ti-user", "ti-trash"} {
		if cut.GlyphIndex(all[name]) != 0 {
			t.Errorf("%s is in the font", name)
		}
	}
	if _, _, _, err := subset(css, woff2, map[string]bool{"ti-nothing": true}); err == nil {
		t.Error("no error without icons")
	}
}

func TestFontOnlyWOFF2(t *testing.T) {
	css, _ := fixture(t)
	got := fontOnlyWOFF2(css)
	if !strings.Contains(got, `font-weight:400;src:url("./fonts/tabler-icons.woff2") format("woff2")}.ti{`) {
		t.Error(got)
	}
	if len(glyphs(got)) != 6 {
		t.Error("rules lost")
	}
}

func write1(t *testing.T, dir, name, content string) {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// The scan finds the icons of the app's packages, of what they import (tabler-templ's alert) and of -dir,
// but not of tests, generated Go code (templ's _templ.go has its .templ) or the output directory.
func TestUsedIcons(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	write1(t, dir, "go.mod", "module example.com/app\n\ngo 1.26\n\nrequire github.com/mind-vm/tabler-templ v0.0.0\n\nreplace github.com/mind-vm/tabler-templ => "+root+"\n")
	if b, err := os.ReadFile(filepath.Join(root, "go.sum")); err == nil {
		write1(t, dir, "go.sum", string(b))
	}
	write1(t, dir, "main.go", "package main\n\nimport (\n\t_ \"embed\"\n\n\t_ \"github.com/mind-vm/tabler-templ/alert\"\n)\n\n//go:embed page.html\nvar page string\n\nvar icon = \"ti-home\"\n\nfunc main() {}\n")
	write1(t, dir, "page.html", `<i class="ti ti-pencil"></i>`)
	write1(t, dir, "view.templ", `<i class="ti ti-star"></i>`)
	write1(t, dir, "view_templ.go", "// Code generated by templ - DO NOT EDIT.\n\npackage main\n\nvar x = \"ti-generated\"\n")
	write1(t, dir, "main_test.go", "package main\n\nvar y = \"ti-in-test\"\n")
	write1(t, dir, "templates/a.gohtml", `<i class="ti ti-user"></i>`)
	write1(t, dir, "templates/node_modules/x.js", `"ti-node"`)
	write1(t, dir, "templates/tabler/icons/tabler-icons.min.css", `.ti-out:before{content:"\ea01"}`)
	write1(t, dir, "templates/tabler/x.js", `"ti-out-js"`)
	t.Chdir(dir)
	t.Setenv("GOFLAGS", "-mod=mod") // the go.mod above lists no indirect modules
	used, err := usedIcons([]string{"./..."}, []string{"templates"}, "templates/tabler")
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"ti-home", "ti-pencil", "ti-star", "ti-user", "ti-alert-circle", "ti-info-circle"} {
		if !used[want] {
			t.Errorf("%s not found", want)
		}
	}
	for _, not := range []string{"ti-generated", "ti-in-test", "ti-node", "ti-out", "ti-out-js"} {
		if used[not] {
			t.Errorf("%s found", not)
		}
	}
}

