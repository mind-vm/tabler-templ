//go:build ignore

// batch_g_gen writes batch_g_data_gen.go: the icon names (@tabler/icons), the flags, the color palette
// and the illustrations of the Tabler preview, read from the pinned Tabler sources. Run it in cmd/demo:
//
//	go run batch_g_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"strings"

	"github.com/mind-vm/tabler-templ/versions"
)

const (
	iconsVersion = versions.Icons
	tablerCommit = versions.TablerCommit
)

func get(url string, v any) {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	if err := json.Unmarshal(b, v); err != nil {
		log.Fatal(err)
	}
}

func data(name string, v any) {
	get("https://raw.githubusercontent.com/tabler/tabler/"+tablerCommit+"/shared/data/"+name, v)
}

// orderedKeys returns the keys of a JSON object in file order.
func orderedKeys(url string) []string {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	dec := json.NewDecoder(resp.Body)
	if _, err := dec.Token(); err != nil {
		log.Fatal(err)
	}
	var keys []string
	for dec.More() {
		t, err := dec.Token()
		if err != nil {
			log.Fatal(err)
		}
		keys = append(keys, t.(string))
		var skip json.RawMessage
		if err := dec.Decode(&skip); err != nil {
			log.Fatal(err)
		}
	}
	return keys
}

func main() {
	iconsURL := "https://cdn.jsdelivr.net/npm/@tabler/icons@" + iconsVersion + "/icons.json"
	var icons map[string]struct {
		Styles map[string]any `json:"styles"`
	}
	get(iconsURL, &icons)
	var outline, filled []string
	for _, k := range orderedKeys(iconsURL) {
		if _, ok := icons[k].Styles["outline"]; ok {
			outline = append(outline, k)
		}
		if _, ok := icons[k].Styles["filled"]; ok {
			filled = append(filled, k)
		}
	}

	var flags []struct{ Name, Flag, Category string }
	data("flags.json", &flags)

	var illustrations []string
	data("illustrations.json", &illustrations)
	var free struct {
		Autodark json.RawMessage `json:"autodark"`
	}
	data("free-illustrations.json", &free)
	freeURL := "https://raw.githubusercontent.com/tabler/tabler/" + tablerCommit + "/shared/data/free-illustrations.json"
	var freeMap map[string]string
	if err := json.Unmarshal(free.Autodark, &freeMap); err != nil {
		log.Fatal(err)
	}
	// The free illustrations' keys in file order (the preview opens with the last one).
	var freeOrder []string
	{
		var top map[string]json.RawMessage
		get(freeURL, &top)
		dec := json.NewDecoder(bytes.NewReader(top["autodark"]))
		dec.Token()
		for dec.More() {
			t, _ := dec.Token()
			freeOrder = append(freeOrder, t.(string))
			var s string
			dec.Decode(&s)
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run batch_g_gen.go; DO NOT EDIT.\n\npackage main\n\n")
	fmt.Fprintf(&b, "// outlineIcons and filledIcons are the icons of @tabler/icons %s in the order of its icons.json.\n", iconsVersion)
	fmt.Fprintf(&b, "var outlineIcons = %#v\n\nvar filledIcons = %#v\n\n", outline, filled)
	b.WriteString("// previewFlags are the flags of the preview (shared/data/flags.json).\nvar previewFlags = []previewFlag{\n")
	for _, f := range flags {
		fmt.Fprintf(&b, "\t{%q, %q, %q},\n", f.Name, f.Flag, f.Category)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "// moreIllustrations are the PNG illustrations of the preview (shared/data/illustrations.json).\nvar moreIllustrations = %#v\n\n", illustrations)
	b.WriteString("// freeIllustrations are the five free SVG illustrations (autodark), in file order.\nvar freeIllustrations = []freeIllustration{\n")
	for _, k := range freeOrder {
		fmt.Fprintf(&b, "\t{%q, %q},\n", k, strings.ReplaceAll(freeMap[k], "\n", ""))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("batch_g_data_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d outline, %d filled icons, %d flags, %d illustrations, %d free", len(outline), len(filled), len(flags), len(illustrations), len(freeOrder))
}
